export function textWidth(text: string): number {
  let w = 0;
  for (const ch of text.toUpperCase()) w += (G[ch]?.[0].length ?? 3) + 1;
  return Math.max(0, w - 1);
}

/** Нарисовать текст; возвращает ширину. */
export function drawText(pc: PixelCanvas, x: number, y: number, text: string, color: Color, shadow?: Color): number {
  let cx = x;
  for (const ch of text.toUpperCase()) {
    const glyph = G[ch] ?? G[' '];
    glyph.forEach((row, j) => {
      for (let i = 0; i < row.length; i++) {
        if (row[i] !== '#') continue;
        if (shadow) pc.px(cx + i + 1, y + j + 1, shadow);
        pc.px(cx + i, y + j, color);
      }
    });
    cx += glyph[0].length + 1;
  }
  return cx - x - 1;
}
